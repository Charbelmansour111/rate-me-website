export function AppTabBar({
  role,
  active,
  lang,
}: {
  role: AppRole;
  active: AppTab;
  /** The language of the screenshot under it. */
  lang: 'en' | 'ar';
}) {
  return (
    <div className="app-tabs" lang={lang} dir={lang === 'ar' ? 'rtl' : 'ltr'} aria-hidden="true">
      {TABS[role].map((tab) => {
        const on = tab === active;
        return (
          <span key={tab} className="app-tab" data-on={on || undefined}>
            <svg viewBox="0 0 512 512">
              {on ? (
                <path d={FILLED[tab]} fill="currentColor" />
              ) : (
                <>
                  {tab === 'profile' ? (
                    <path d={OUTLINE[tab]} fill="currentColor" />
                  ) : (
                    <path
                      d={OUTLINE[tab]}
                      fill="none"
                      stroke="currentColor"
                      strokeWidth="32"
                      strokeLinecap="round"
                      strokeLinejoin="round"
                    />
                  )}
                  {tab === 'calendar' && <path d={CALENDAR_DOTS} fill="currentColor" />}
                </>
              )}
            </svg>
            <span>{LABELS[lang][tab]}</span>
          </span>
        );
      })}
    </div>
  );
}
